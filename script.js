let currentLang = "ru";
let currentFilter = "all";
const $ = id => document.getElementById(id);
function renderCards(){
  const t = translations[currentLang];
  const query = $("search").value.trim().toLocaleLowerCase();
  const cards = t.cards.filter(c => (currentFilter === "all" || c[0] === currentFilter) &&
    (c[1] + " " + c[2] + " " + c[3]).toLocaleLowerCase().includes(query));
  $("materials-grid").innerHTML = cards.map((c,i) => `
    <article class="material-card">
      <div class="material-top"><span class="material-icon tone-${c[5]}">${c[4]}</span><span class="material-type">${t.types[c[0]]}</span></div>
      <h3>${c[1]}</h3><p>${c[2]}</p>
      <div class="material-footer"><span class="material-meta">${c[3]}</span><a class="material-link" href="#" data-placeholder="true">${t.open} ↗</a></div>
    </article>`).join("");
  $("empty-state").hidden = cards.length > 0;
  document.querySelectorAll("[data-placeholder]").forEach(a => a.addEventListener("click", e => {
    e.preventDefault(); alert(t.placeholder + ".\n\n" + (currentLang === "ru" ? "Преподаватель может добавить ссылку в script.js." : currentLang === "kk" ? "Оқытушы script.js файлына сілтеме қоса алады." : "The instructor can add a link in script.js."));
  }));
}
function setLanguage(lang){
  currentLang = lang;
  const t = translations[lang];
  document.documentElement.lang = lang === "kk" ? "kk" : lang;
  const map = {
    "brand-subtitle":"subtitle","hero-eyebrow":"eyebrow","hero-title":"title","hero-text":"heroText",
    "hero-button":"heroButton","art-card-one":"artOne","art-card-two":"artTwo",
    "stat-one-title":"stat1","stat-one-sub":"stat1s","stat-two-title":"stat2","stat-two-sub":"stat2s",
    "stat-three-title":"stat3","stat-three-sub":"stat3s","section-eyebrow":"sectionEyebrow",
    "section-title":"sectionTitle","section-description":"sectionDesc","filter-all":"all",
    "filter-lecture":"lecture","filter-practice":"practice","filter-test":"test",
    "empty-state":"empty","teacher-note-title":"noteTitle","teacher-note-text":"noteText",
    "cta-eyebrow":"ctaEyebrow","cta-title":"ctaTitle","cta-button":"ctaButton","footer-text":"footer"
  };
  Object.entries(map).forEach(([id,key]) => $(id).innerHTML = t[key]);
  $("search").placeholder = t.search;
  document.querySelectorAll(".lang").forEach(b => b.classList.toggle("active", b.dataset.lang === lang));
  renderCards();
}
document.querySelectorAll(".lang").forEach(b => b.addEventListener("click", () => setLanguage(b.dataset.lang)));
document.querySelectorAll(".filter").forEach(b => b.addEventListener("click", () => {
  currentFilter = b.dataset.filter;
  document.querySelectorAll(".filter").forEach(x => x.classList.toggle("active", x === b));
  renderCards();
}));
$("search").addEventListener("input", renderCards);
$("year").textContent = new Date().getFullYear();
$("menu-toggle").addEventListener("click", () => {
  document.body.classList.toggle("menu-open");
  $("materials").scrollIntoView({behavior:"smooth"});
});
setLanguage("ru");
